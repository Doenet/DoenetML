#!/usr/bin/env python3
"""Collect criterion estimates and stats into results/raw/ and regenerate
RESULTS.md. Hand-written commentary lives in results/NOTES.md and is included
verbatim so the tables never drift from the numbers.

Usage: scripts/render-results.py [--label NAME]
"""
import json, os, platform, subprocess, sys, datetime, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRIT = ROOT / "target/criterion"
RAW = ROOT / "results/raw"
RAW.mkdir(parents=True, exist_ok=True)

def spec_key(spec):
    shape, _, size = spec.partition("-")
    a, _, b = size.partition("x")
    return (shape, int(a or 0), int(b or 0))

def collect_criterion():
    out = {}
    for est in CRIT.glob("*/*/*/new/estimates.json"):
        group, func, param = est.parts[-5], est.parts[-4], est.parts[-3]
        d = json.loads(est.read_text())
        out.setdefault(group, {}).setdefault(func, {})[param] = {
            "mean_ns": d["mean"]["point_estimate"],
            "median_ns": d["median"]["point_estimate"],
            "std_dev_ns": d["std_dev"]["point_estimate"],
        }
    return out

def collect_stats():
    p = RAW / "stats.jsonl"
    if not p.exists():
        return {}
    return {json.loads(l)["spec"]: json.loads(l) for l in p.read_text().splitlines() if l.strip()}

def collect_latest(pattern):
    files = sorted(RAW.glob(pattern))
    if not files:
        return None
    return json.loads(files[-1].read_text())

def renderer(r):
    """The graph renderer a browser row was measured with (plan 7); rows
    from before plan 7 have none and used the SVG renderer."""
    name = r.get("renderer", "svg")
    return name + ("/element" if r.get("jsxUpdate") == "element" else "")

def collect_e2e():
    """Every e2e run merged by configuration, the newest run winning, so a
    partial sweep (one renderer, a few fixtures) does not hide the rest."""
    files = sorted(RAW.glob("e2e-*.json"))
    if not files:
        return None
    rows, steps, date = {}, None, None
    for f in files:
        d = json.loads(f.read_text())
        steps, date = d.get("steps", steps), d["date"]
        for r in d["results"]:
            key = (r["spec"], r.get("fmt", "json"), r.get("backend", "main"), r["evaluator"], renderer(r), r.get("remount", False))
            rows[key] = {**r, "date": d["date"]}
    return {"date": date, "steps": steps, "results": list(rows.values())}

def cpu_name():
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor()

def sh(cmd):
    try:
        return subprocess.check_output(cmd, shell=True, text=True, cwd=ROOT).strip()
    except subprocess.CalledProcessError:
        return "?"

def fmt_ms(ns):
    return f"{ns/1e6:.2f}" if ns is not None else "–"

def fmt_us(ns):
    return f"{ns/1e3:.2f}" if ns is not None else "–"

def main():
    label = None
    if "--label" in sys.argv:
        label = sys.argv[sys.argv.index("--label") + 1]
    crit = collect_criterion()
    stats = collect_stats()
    meta = {
        "date": datetime.date.today().isoformat(),
        "label": label,
        "cpu": cpu_name(),
        "rustc": sh("rustc --version"),
        "commit": sh("git rev-parse --short HEAD"),
    }
    stamp = meta["date"] + (f"-{label}" if label else "")
    (RAW / f"{stamp}-bench.json").write_text(json.dumps({"meta": meta, "criterion": crit, "stats": stats}, indent=1))

    specs = sorted(set(stats) | {p for g in crit.values() for f in g.values() for p in f}, key=spec_key)
    md = []
    md.append("# Results\n")
    md.append(f"Generated by `scripts/render-results.py` on {meta['date']} at commit `{meta['commit']}`.  ")
    md.append(f"CPU: {meta['cpu']}. {meta['rustc']}.\n")
    md.append("Parsing DoenetML text to DAST is excluded from every number below (it is the existing TypeScript parser and out of scope). Startup begins with the DAST JSON string in memory.\n")

    notes = ROOT / "results/NOTES.md"
    if notes.exists():
        md.append(notes.read_text().rstrip() + "\n")

    if stats:
        md.append("## Document structure and memory\n")
        md.append("*core KB* is the loaded document's heap: cells, program, columnar component tables and the string table (names and text).\n")
        md.append("| fixture | cells | essential | instructions | components | JSON KB | binary KB | core KB | of which strings KB | bytes/cell |")
        md.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        for s in specs:
            d = stats.get(s)
            if not d:
                continue
            md.append(f"| {s} | {d['cells']} | {d['essential']} | {d['instrs']} | {d['components']} | {d['json_bytes']//1024} | {d.get('binary_bytes', 0)//1024} | {d['bytes_total']//1024} | {d.get('bytes_strings', 0)//1024} | {d['bytes_total']/d['cells']:.0f} |")
        md.append("")

    st = crit.get("startup", {})
    if st:
        md.append("## Startup (ms, criterion mean)\n")
        md.append("*deserialize* is DAST JSON; *deserialize binary* is the CDST wire format (ADR 0002). Both feed the same build.\n")
        md.append("| fixture | cells | deserialize JSON | deserialize binary | build | schedule | initial compute | total from JSON | total from binary |")
        md.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
        for s in specs:
            row = [st.get(f, {}).get(s, {}).get("mean_ns") for f in ("deserialize", "deserialize_binary", "build", "schedule", "initial_compute", "total_from_json", "total_from_binary")]
            if all(r is None for r in row):
                continue
            cells = stats.get(s, {}).get("cells", "")
            md.append(f"| {s} | {cells} | " + " | ".join(fmt_ms(r) for r in row) + " |")
        md.append("")

    tk = crit.get("tick", {})
    if tk:
        md.append("## Drag tick (µs per request, criterion mean)\n")
        md.append("One request on the drag target (chain end, fan-out root, or first point), inverted to its essential cell, then recompute with each strategy.\n")
        evs = ["full", "dirty-closure"]
        md.append("| fixture | derived cells | " + " | ".join(evs) + " |")
        md.append("|---|---:|" + "---:|" * len(evs))
        for s in specs:
            row = [tk.get(e, {}).get(s, {}).get("mean_ns") for e in evs]
            if all(r is None for r in row):
                continue
            md.append(f"| {s} | {stats.get(s, {}).get('instrs', '')} | " + " | ".join(fmt_us(r) for r in row) + " |")
        md.append("")
        # Chain-length budget: extrapolate the longest chain's tick linearly to 50 ms.
        chains = [(spec_key(s)[1], tk.get("full", {}).get(s, {}).get("mean_ns")) for s in specs if s.startswith("chain-")]
        chains = [(l, ns) for l, ns in chains if ns]
        if chains:
            l, ns = max(chains)
            md.append(f"Longest measured chain: {l} operators at {fmt_ms(ns)} ms per tick (full recompute). Linear extrapolation puts the 50 ms budget at roughly {int(l * 50e6 / ns):,} serial operators, ignoring the renderer.\n")

    rb = crit.get("rebuild", {}).get("count-change", {})
    if rb:
        md.append("## Structural tick: rebuild on an iteration-count change (ms, criterion mean)\n")
        md.append("One request that changes a repeat's `length` input by one, followed by the whole-document rebuild it triggers (ADR 0004): build, schedule and recompute, with essential values carried over by key. Native, no renderer.\n")
        md.append("| fixture | components | cells | rebuild tick |")
        md.append("|---|---:|---:|---:|")
        for s in specs:
            d = rb.get(s)
            if not d:
                continue
            st_ = stats.get(s, {})
            md.append(f"| {s} | {st_.get('components', '')} | {st_.get('cells', '')} | {fmt_ms(d['mean_ns'])} |")
        md.append("")

    e2e = collect_e2e()
    if e2e:
        md.append("## Browser end to end (headless Chromium, Playwright)\n")
        md.append(f"Measured between {min(r['date'] for r in e2e['results'])} and {e2e['date']} (each row is the latest run of its configuration): load the fixture, then drag the target point for {e2e['steps']} pointer moves. Startup here includes fetching the JSON, wasm instantiation, the core stages, manifest construction and React's first render.\n")
        md.append("Startup is shown for the `full` evaluator only (the evaluator does not affect loading). *worker* is spawn, module load and the document transfer into the worker; *tables* is creating the component-table views (main thread) or copying the columns out of the worker.\n")
        md.append("Plan 7 rows (a renderer other than `svg`, or `svg` measured with `paint`) were run with `dirty-closure` only and are shown under that evaluator.\n")
        md.append("| fixture | renderer | format | backend | cells | components | fetch | worker | wasm init | core total | tables | first render | total (ms) |")
        md.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        plan7 = lambda r: "renderer" in r
        for r in sorted(e2e["results"], key=lambda r: (spec_key(r["spec"]), renderer(r), r.get("fmt", "json"), r.get("backend", "main"))):
            if r["evaluator"] != ("dirty-closure" if plan7(r) else "full"):
                continue
            t = r["timings"] or {}
            num = lambda x: x if isinstance(x, (int, float)) and x == x else 0.0
            manifest = num(t.get("manifest")) + num(t.get("manifestTransfer"))
            parts = [t.get("fetch"), t.get("workerSpawn"), t.get("wasmInit"), t.get("coreTotal"), manifest, t.get("firstRender")]
            total = sum(num(x) for x in parts)
            md.append(f"| {r['spec']} | {renderer(r)} | {r.get('fmt', 'json')} | {r.get('backend', 'main')} | {r['nCells']} | {r['nComponents']} | " + " | ".join(f"{x:.1f}" if isinstance(x, (int, float)) and x == x else "–" for x in parts) + f" | {total:.1f} |")
        md.append("")
        md.append("Per drag step, in ms. *Core* is the time inside the wasm request call, measured where the core runs. *Round trip* is until the changed cells are readable on the main thread. *Commit* is until React committed the resulting DOM updates. *Frame* is until the next animation frame.\n")
        md.append("Tick timings are independent of the wire format, so only the binary-format runs are shown.\n")
        md.append("*Renderer* is how graphs are drawn (plan 7): `svg` is the hand-drawn SVG renderer every row before plan 7 used; `jsxgraph` and `jsxgraph-canvas` are JSXGraph with Doenet's look; `/element` is Doenet's own update pattern. *Paint* (plan 7 rows only) is until a task after that frame, so it includes the browser's style, layout and paint of the tick's DOM changes.\n")
        md.append("| fixture | renderer | backend | evaluator | changed cells | core p50 | round trip p50 | commit p50 | commit p90 | frame p50 | frame p90 | frame max | paint p50 | paint p90 |")
        md.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        nan = {"p50": float("nan"), "p90": float("nan")}
        for r in sorted(e2e["results"], key=lambda r: (spec_key(r["spec"]), renderer(r), r.get("backend", "main"), r["evaluator"])):
            if r.get("fmt", "cdast") != "cdast":
                continue
            k = r["tick"]
            rt = k.get("roundTrip", {}).get("p50", float("nan"))
            pt = k.get("paint", nan)
            md.append(f"| {r['spec']} | {renderer(r)} | {r.get('backend', 'main')} | {r['evaluator']} | {k['changed']['p50']:.0f} | {k['core']['p50']:.3f} | {rt:.2f} | {k['commit']['p50']:.2f} | {k['commit']['p90']:.2f} | {k['frame']['p50']:.2f} | {k['frame']['p90']:.2f} | {k['frame']['max']:.2f} | {pt['p50']:.2f} | {pt['p90']:.2f} |".replace("nan", "–"))
        md.append("")

        rebuilds = [r for r in e2e["results"] if r.get("rebuild") and r.get("fmt", "cdast") == "cdast"]
        if rebuilds:
            md.append("Structural ticks: the repeat's `length` input is changed by one, 20 times, so every request rebuilds the document in the core and the renderer re-reads the component table. *Core* includes the rebuild. *Remount* rows throw the React tree away and rebuild it; the others key children by stable component identity and update in place.\n")
            md.append("| fixture | renderer | backend | remount | cells | components | core p50 | round trip p50 | commit p50 | commit p90 | frame p50 | frame p90 | paint p50 |")
            md.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
            for r in sorted(rebuilds, key=lambda r: (spec_key(r["spec"]), renderer(r), r.get("backend", "main"), r.get("remount", False))):
                k = r["rebuild"]
                md.append(f"| {r['spec']} | {renderer(r)} | {r.get('backend', 'main')} | {'yes' if r.get('remount') else 'no'} | {r['nCells']} | {r['nComponents']} | {k['core']['p50']:.2f} | {k['roundTrip']['p50']:.2f} | {k['commit']['p50']:.1f} | {k['commit']['p90']:.1f} | {k['frame']['p50']:.1f} | {k['frame']['p90']:.1f} | {k.get('paint', nan)['p50']:.1f} |".replace("nan", "–"))
            md.append("")
        toggles = [r for r in e2e["results"] if r.get("toggle") and r.get("fmt", "cdast") == "cdast"]
        if toggles:
            md.append("Boolean toggles: one `booleanInput` bound to every point's `hide`, flipped 20 times. The 0/1 cell is an ordinary `f64` cell; the cost is the renderer mounting and unmounting N circles.\n")
            md.append("| fixture | renderer | backend | changed cells | core p50 | commit p50 | frame p50 | frame p90 | paint p50 |")
            md.append("|---|---|---|---:|---:|---:|---:|---:|---:|")
            for r in sorted(toggles, key=lambda r: (spec_key(r["spec"]), renderer(r), r.get("backend", "main"))):
                k = r["toggle"]
                md.append(f"| {r['spec']} | {renderer(r)} | {r.get('backend', 'main')} | {k['changed']['p50']:.0f} | {k['core']['p50']:.3f} | {k['commit']['p50']:.1f} | {k['frame']['p50']:.1f} | {k['frame']['p90']:.1f} | {k.get('paint', nan)['p50']:.1f} |".replace("nan", "–"))
            md.append("")

    base = collect_latest("baseline-*.json")
    if base:
        md.append("## Baseline: the current DoenetML core (JS core, standalone bundle)\n")
        md.append(f"Measured on {base['date']} with the standalone bundle at `{base['standalone']}`. The same generated documents, with each `<op>` rewritten as a `<number>` holding the equivalent math expression (chains lose their final clamp). *init* is from `renderDoenetViewerToContainer` to `initializedCallback`. *movePoint* is the core's own action API awaited {base['steps']} times; *DOM* is until the last attribute mutation on the graph after each action. The pointer drag is {base['steps']} real mouse moves; the current renderer offers no per-tick hook, so only wall time per move is reported.\n")
        md.append("| fixture | init (ms) | first point in DOM (ms) | movePoint p50 | movePoint p90 | DOM p50 | frame p50 | pointer drag ms/move |")
        md.append("|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in sorted(base["results"], key=lambda r: spec_key(r["spec"])):
            if r.get("error"):
                md.append(f"| {r['spec']} | failed: {r['error']} | | | | | | |")
                continue
            if "slider" in r:
                continue
            a = r["action"]
            md.append(f"| {r['spec']} | {r['init_ms']:.0f} | {r.get('first_point_ms', float('nan')):.0f} | {a['core']['p50']:.2f} | {a['core']['p90']:.2f} | {a['dom']['p50']:.2f} | {a['frame']['p50']:.2f} | {r['drag']['ms_per_move']:.1f} |")
        md.append("")
        sliders = [r for r in base["results"] if r.get("slider")]
        if sliders:
            md.append("Slider-driven documents in the current core, through the slider's own `changeValue` action. For `sliderchain` the slider is bound through the chain to a mathInput; for `repeat` the slider is the repeat's `length`, so each action changes the number of points (the current core's replacement update, the prototype's rebuild).\n")
            md.append("| fixture | init (ms) | first point in DOM (ms) | changeValue p50 | changeValue p90 | DOM p50 | frame p50 |")
            md.append("|---|---:|---:|---:|---:|---:|---:|")
            for r in sorted(sliders, key=lambda r: spec_key(r["spec"])):
                a = r["slider"]
                md.append(f"| {r['spec']} | {r['init_ms']:.0f} | {r.get('first_point_ms', float('nan')):.0f} | {a['core']['p50']:.2f} | {a['core']['p90']:.2f} | {a['dom']['p50']:.2f} | {a['frame']['p50']:.2f} |")
            md.append("")

    diff = collect_latest("slider-diff-*.json")
    if diff:
        md.append("## Differential test: slider behavior against the current core\n")
        md.append(f"Measured on {diff['date']} by `web/baseline/slider-diff.mjs`: the same slider documents and the same sequence of requests run through both cores (the current core through its `changeValue` and mathInput actions, the prototype through cell requests), comparing the observed `value`s after every step to 1e-9.\n")
        md.append("| scenario | steps | differing | first difference |")
        md.append("|---|---:|---:|---|")
        total = 0
        bad = 0
        for r in diff["results"]:
            if r.get("error"):
                md.append(f"| {r['name']} | failed: {r['error']} | | |")
                continue
            rows = r["rows"]
            diffs = [x for x in rows if not x["ok"]]
            total += len(rows)
            bad += len(diffs)
            md.append(f"| {r['name']} | {len(rows)} | {len(diffs)} | {diffs[0]['label'] if diffs else ''} |")
        md.append("")
        md.append(f"{bad} of {total} observations differ.\n")

    (ROOT / "RESULTS.md").write_text("\n".join(md))
    print(f"wrote RESULTS.md and {RAW / (stamp + '-bench.json')}")

if __name__ == "__main__":
    main()
